package me.jsjlog.blog.notification.domain;

/**
 * 알림 종류.
 *
 * <p>전부 "나를 기다리는 일" 이다. 안 보면 대화가 끊기거나, 해야 할 일이 밀린다.
 * 좋아요는 넣지 않는다 — 안 봐도 아무 일이 일어나지 않고, 열 개 눌리면 알림이 열 개가 되어
 * 묶는 처리를 따로 만들어야 한다. 싫어요는 어느 경우에도 알리지 않는다.
 * 기분만 상하고 할 수 있는 일이 없다.</p>
 *
 * <p>앞의 둘은 회원에게, 뒤의 둘은 각각 운영자와 가려진 사람에게 간다. 받는 사람이 달라도
 * 저장 구조는 같다 — 관리자도 회원이라 {@code recipient} 하나로 충분하다.</p>
 *
 * <p>종을 나누지 않는다. 관리자도 사람 하나라, 신고와 답글이 한 목록에 같이 떠도 된다.
 * 나눠 두면 어느 화면에 있느냐에 따라 못 보는 알림이 생긴다.</p>
 */
public enum NotificationType {

    /** 내 댓글에 답글이 달렸다 */
    REPLY,

    /** 내 글에 댓글이 달렸다 */
    POST_COMMENT,

    /**
     * 댓글 신고가 들어왔다. 운영자에게 간다.
     *
     * <p>신고를 받고도 자동으로 숨기지 않기로 했다 — 몰려서 신고하면 신고가 공격 수단이
     * 되기 때문이다. 그 판단은 "사람이 본다" 를 전제로 하는데, 이 알림이 그 전제다.
     * 이것이 없으면 "자동 숨김을 안 함" 이 아니라 "아무 조치도 안 함" 이 된다.</p>
     */
    REPORT_RECEIVED,

    /**
     * 내 댓글이 운영자에게 가려졌다.
     *
     * <p>가려진 댓글은 공개 화면에서 답글이 없으면 흔적 없이 사라진다. 알려 주지 않으면
     * 안 써진 줄 알고 다시 쓰고, 또 가려지고, 또 쓴다.</p>
     *
     * <p><b>사유는 싣지 않는다.</b> 어떤 댓글에 누가 왜 신고했는지가 좁혀진다.</p>
     */
    COMMENT_HIDDEN
}
